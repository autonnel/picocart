export type RoundingRule = 'none' | 'integer' | '99' | '95';

export interface CurrencyRate {
  rate: number;
  rounding: RoundingRule;
}

export const ROUNDING_RULES: readonly RoundingRule[] = ['none', 'integer', '99', '95'];

const ZERO_DECIMAL_CURRENCIES = new Set(['JPY', 'KRW', 'VND', 'CLP', 'ISK', 'HUF']);

export function isZeroDecimal(currencyCode: string): boolean {
  return ZERO_DECIMAL_CURRENCIES.has(currencyCode.toUpperCase());
}

// Decimal columns come back as "60" or 59.9; the editor shows them with the currency's fixed decimals.
export function formatPriceInput(value: unknown, currencyCode: string): string {
  if (value === null || value === undefined || value === '') return '';
  const amount = Number(value);
  if (!Number.isFinite(amount)) return String(value);
  return amount.toFixed(isZeroDecimal(currencyCode) ? 0 : 2);
}

function ceilToEnding(cents: number, ending: number): number {
  return Math.max(0, Math.ceil((cents - ending) / 100)) * 100 + ending;
}

export function convertPrice(base: string, rate: CurrencyRate, currencyCode: string): string {
  const baseCents = Math.round(Number(base) * 100);
  let cents = Math.ceil(baseCents * rate.rate - 1e-9);
  if (cents === 0) return '0.00';
  const rounding = isZeroDecimal(currencyCode) ? 'integer' : rate.rounding;
  if (rounding === 'integer') cents = Math.ceil(cents / 100) * 100;
  else if (rounding === '99') cents = ceilToEnding(cents, 99);
  else if (rounding === '95') cents = ceilToEnding(cents, 95);
  return (cents / 100).toFixed(2);
}

export function forceDefaultCurrencyManual<
  V extends { prices?: { currencyCode: string; isManual?: boolean }[] },
>(variants: V[], defaultCurrency: string): V[] {
  return variants.map((v) =>
    v.prices
      ? {
          ...v,
          prices: v.prices.map((p) =>
            p.currencyCode === defaultCurrency ? { ...p, isManual: true } : p,
          ),
        }
      : v,
  );
}

// Auto rows are regenerated by syncAutoPrices only for rated currencies; an auto row of a currency
// without a rate would be dropped, so it is written (as manual, the column default) with the submitted value.
export function pricesToWrite<P extends { currencyCode: string; isManual?: boolean }>(
  prices: P[],
  rates: Record<string, CurrencyRate>,
): P[] {
  return prices.filter((p) => p.isManual !== false || !Object.hasOwn(rates, p.currencyCode));
}
